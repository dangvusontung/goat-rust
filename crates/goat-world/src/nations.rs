#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn nation_list_is_fifty_and_sane() {
        assert_eq!(NATIONS.len(), 50, "spec: exactly 50 nations");
        for n in NATIONS {
            assert!((1..=99).contains(&n.power), "{} power out of range", n.name);
            assert!(
                (3..=4).contains(&n.divisions),
                "{} divisions out of spec",
                n.name
            );
            let combos = n.cities.len() * patterns_for(n.style).len();
            assert!(
                combos >= n.divisions as usize * 16,
                "{} cannot name {} clubs from {} combos",
                n.name,
                n.divisions as usize * 16,
                combos
            );
        }
    }

    #[test]
    fn tiers_are_ordered() {
        // Tier anchors: every T1 nation out-powers every T3-and-below nation,
        // and every T1/T2 nation out-powers every T5 nation.
        let min_t1 = NATIONS[..5].iter().map(|n| n.power).min().unwrap();
        let max_t5 = NATIONS[33..].iter().map(|n| n.power).max().unwrap();
        assert!(
            min_t1 > max_t5,
            "weakest elite must out-power strongest minnow"
        );
    }
}
