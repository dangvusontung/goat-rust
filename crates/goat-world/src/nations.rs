//! Static nation metadata for procedural world generation (World Scale-Up Phase A).
//!
//! 50 real nations (geographic data, not IP), each with a hand-tiered
//! `nation_power` (UEFA-coefficient-style hierarchy — same tiers in every
//! world, NOT seed-driven), a club-naming style, and a pool of city names
//! that the genesis-time club-name generator draws from.
//!
//! This table is the "authoring-time data" of Bible §7.2: it can be enriched
//! offline (e.g. by an LLM authoring pass emitting the same schema) without
//! touching runtime code.

/// Club-naming flavor family. Patterns are football-generic forms
/// ("X United", "Real X", "AC X"...) combined with city names.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum NameStyle {
    English,
    Spanish,
    Portuguese,
    German,
    Italian,
    French,
    Dutch,
    Generic,
}

/// One nation's static definition.
pub struct NationDef {
    pub name: &'static str,
    /// 1–99, hand-assigned by tier (decision 4 in docs/WORLD-SCALE-UP.md).
    pub power: u8,
    /// Number of divisions in this nation's pyramid (3 or 4).
    pub divisions: u8,
    pub style: NameStyle,
    /// City pool for club names. 12+ cities × 8 patterns >= 64 unique names,
    /// enough for the largest pyramid (4 divisions × 16 clubs).
    pub cities: &'static [&'static str],
}

